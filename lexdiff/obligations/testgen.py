"""Generate locked obligation tests from approved obligations.

Once written, a test file is hash-locked. Overwriting it needs a named human approver and
is recorded in compliance/test_changes.yaml (the audit trail of every approved test rewrite).
"""
from __future__ import annotations

import json
from pathlib import Path

import yaml

from ..util import norm_ws, sha256_bytes, sha256_file
from .model import Obligation, now_iso

CALL = {
    "route_requires_mfa": "testkit.assert_route_requires_mfa(self, {method!r}, {path!r})",
    "canary_clean": "testkit.assert_canary_clean(self, {store!r})",
    "ftc_notice": "testkit.assert_ftc_notice(self, days={days}, min_consumers={min_consumers})",
}


class LockedTestError(RuntimeError):
    pass


def test_filename(ob: Obligation) -> str:
    return f"test_{ob.id.lower().replace('-', '')}.py"


def render(ob: Obligation) -> str:
    lines = [
        "# AUTO-GENERATED by `lexdiff gen-tests`. Locked once approved; do not edit by hand.",
        f"# Obligation {ob.id} | 16 CFR {ob.clause}",
        f"# Quote: {norm_ws(ob.quote)}",
        "import unittest",
        "",
        "from lexdiff import testkit",
        "",
        "",
        f"class Test{ob.id.replace('-', '')}(unittest.TestCase):",
    ]
    for c in ob.checks:
        lines += [f"    def {c['name']}(self):", "        " + CALL[c["type"]].format(**c), ""]
    return "\n".join(lines).rstrip() + "\n"


def _load_lock(lock_path: Path) -> dict:
    return json.loads(lock_path.read_text()) if lock_path.exists() else {}


def generate(obligations, tests_dir, lock_path, changes_path=None, allow_rewrite_by="", reason="") -> list[Path]:
    tests_dir, lock_path = Path(tests_dir), Path(lock_path)
    tests_dir.mkdir(parents=True, exist_ok=True)
    lock = _load_lock(lock_path)
    written, rewrites = [], []
    for ob in obligations:
        if ob.status != "approved" or not ob.checks:
            continue
        content = render(ob)
        path = tests_dir / test_filename(ob)
        new_sha = sha256_bytes(content.encode())
        if path.name in lock and lock[path.name] != new_sha:
            if not allow_rewrite_by.strip():
                raise LockedTestError(
                    f"{path.name} is locked; regenerating it would change a locked test. "
                    "Re-run with --allow-rewrite --by <approver> --reason <why> to record a human-approved rewrite.")
            rewrites.append({"file": path.name, "old_sha256": lock[path.name], "new_sha256": new_sha,
                             "approved_by": allow_rewrite_by.strip(), "reason": reason or "unspecified", "at": now_iso()})
        path.write_text(content, encoding="utf-8")
        written.append(path)
    if rewrites and changes_path:
        changes_path = Path(changes_path)
        existing = (yaml.safe_load(changes_path.read_text()) or []) if changes_path.exists() else []
        changes_path.write_text(yaml.safe_dump(existing + rewrites, sort_keys=False), encoding="utf-8")
    write_lock(tests_dir, lock_path)
    return written


def write_lock(tests_dir, lock_path) -> dict:
    lock = {p.name: sha256_file(p) for p in sorted(Path(tests_dir).glob("test_*.py"))}
    Path(lock_path).parent.mkdir(parents=True, exist_ok=True)
    Path(lock_path).write_text(json.dumps(lock, indent=2) + "\n")
    return lock
